function at(root, path, props, type) {
  const n = JCR.ensure(root, path, type);
  Object.assign(n.props, props || {});
  return n;
}

function fileAt(root, path, data, mime) {
  at(root, path, { 'jcr:primaryType': 'nt:file' });
  at(root, path + '/jcr:content', { 'jcr:primaryType': 'nt:resource', 'jcr:mimeType': mime || 'text/plain', 'jcr:data': data });
}

