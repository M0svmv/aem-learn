// Copies a design model (/conf/global/...) to its runtime copy (/var/workflow/models/...)
function syncModelIn(root, id) {
  const d = JCR.get(root, `/conf/global/settings/workflow/models/${id}/jcr:content`);
  if (!d) return false;
  const runtime = JCR.node(id, { 'jcr:primaryType': 'cq:WorkflowModel', title: d.props['jcr:title'], description: d.props['jcr:description'] || '' });
  const flow = JCR.get(d, 'flow');
  runtime.children.push(JCR.node('nodes', {}, (flow ? flow.children : []).map(s => JCR.node(s.name, { ...s.props }))));
  JCR.put(root, '/var/workflow/models', runtime);
  d.props.lastSynced = new Date().toISOString();
  return true;
}

