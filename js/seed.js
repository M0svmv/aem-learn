// (Re)creates the rollout configs with their action nodes, like CRXDE shows them
function seedRolloutConfigs(root) {
  const base = '/libs/msm/wcm/rolloutconfigs';
  const n = JCR.get(root, base);
  if (n && ROLLOUT_CONFIGS.every(([name]) => JCR.get(n, name) && JCR.get(n, name).children.length)) return false;
  at(root, base, { 'jcr:primaryType': 'sling:Folder' });
  for (const [name, title, trigger, actions, desc] of ROLLOUT_CONFIGS) {
    JCR.put(root, base, JCR.node(name, { 'jcr:primaryType': 'cq:RolloutConfig', 'jcr:title': title, 'cq:trigger': trigger, 'jcr:description': desc },
      actions.map(a => JCR.node(a, { 'jcr:primaryType': 'cq:LiveSyncAction' }))));
  }
  const order = ROLLOUT_CONFIGS.map(c => c[0]);
  JCR.get(root, base).children.sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name));
  return true;
}

